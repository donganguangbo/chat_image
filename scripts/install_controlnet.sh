#!/usr/bin/env bash
#
# install_controlnet.sh
#
# Installs the ControlNet + DWPose hard-constraint pose chain:
#   1. comfyui_controlnet_aux custom node → template + every isolated instance
#   2. DWPose ONNX models (yolox_l, dw-ll_ucoco_384) → central models/dwpose/,
#      symlinked into each node's ckpts/ dir
#   3. FLUX.1-dev-Controlnet-Union model → models/controlnet/ (auto-picked up
#      by every ComfyUI instance via configure_comfy_paths.py)
#
# Idempotent: skips any step whose artifact already exists.
# Does NOT restart ComfyUI — run `scripts/start_multi_stack.sh` afterward.
#
# Environment overrides:
#   PROJECT_ROOT=/root/autodl-tmp/projects/chat_image
#   PYTHON_BIN=$PROJECT_ROOT/venv/bin/python
#   HF_TOKEN=<optional huggingface token for higher rate limits>
#
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="${PROJECT_ROOT:-$(cd "$SCRIPT_DIR/.." && pwd)}"
PYTHON_BIN="${PYTHON_BIN:-$PROJECT_ROOT/venv/bin/python}"
PIP_BIN="${PIP_BIN:-${PYTHON_BIN%/*}/pip}"

COMFY_NODE_REPO="https://github.com/Fannovel16/comfyui_controlnet_aux.git"
COMFY_NODE_NAME="comfyui_controlnet_aux"

# Central model paths (auto-shared across all isolated instances via
# extra_model_paths.yaml generated by configure_comfy_paths.py)
MODELS_ROOT="$PROJECT_ROOT/models"
DWPOSE_DIR="$MODELS_ROOT/dwpose"
CONTROLNET_DIR="$MODELS_ROOT/controlnet"

# Downloads
YOLOX_URL="https://huggingface.co/yzd-v/DWPose/resolve/main/yolox_l.onnx"
DWLL_URL="https://huggingface.co/yzd-v/DWPose/resolve/main/dw-ll_ucoco_384.onnx"
FLUX_CN_URL="https://huggingface.co/InstantX/FLUX.1-dev-Controlnet-Union/resolve/main/diffusion_pytorch_model.safetensors"
FLUX_CN_FILE="flux-controlnet-union.safetensors"

log() { echo "[install_controlnet] $*"; }
die() { echo "[install_controlnet][error] $*" >&2; exit 1; }

# --------------------------------------------------------------------
# 0. Preflight
# --------------------------------------------------------------------
[[ -d "$PROJECT_ROOT" ]] || die "PROJECT_ROOT not found: $PROJECT_ROOT"
[[ -x "$PYTHON_BIN" ]] || die "Python not executable: $PYTHON_BIN"
command -v git >/dev/null 2>&1 || die "git is required"
command -v curl >/dev/null 2>&1 || die "curl is required"

log "PROJECT_ROOT = $PROJECT_ROOT"
log "PYTHON_BIN   = $PYTHON_BIN"

# --------------------------------------------------------------------
# 1. Collect all custom_nodes/ target directories
#    - template: $PROJECT_ROOT/ComfyUI/custom_nodes/
#    - each isolated instance: $PROJECT_ROOT/isolated/comfy_*/app/custom_nodes/
# --------------------------------------------------------------------
declare -a NODE_TARGETS
if [[ -d "$PROJECT_ROOT/ComfyUI" ]]; then
  NODE_TARGETS+=("$PROJECT_ROOT/ComfyUI/custom_nodes")
fi

shopt -s nullglob
for inst in "$PROJECT_ROOT"/isolated/comfy_*/app; do
  [[ -d "$inst" ]] || continue
  NODE_TARGETS+=("$inst/custom_nodes")
done
shopt -u nullglob

if [[ ${#NODE_TARGETS[@]} -eq 0 ]]; then
  die "no custom_nodes directory found (neither ComfyUI/ nor isolated/comfy_*/app/)"
fi

log "found ${#NODE_TARGETS[@]} custom_nodes target(s):"
for t in "${NODE_TARGETS[@]}"; do log "  - $t"; done

# --------------------------------------------------------------------
# 2. Clone / update comfyui_controlnet_aux into each target
# --------------------------------------------------------------------
for target in "${NODE_TARGETS[@]}"; do
  mkdir -p "$target"
  node_dir="$target/$COMFY_NODE_NAME"
  if [[ -d "$node_dir/.git" ]]; then
    log "[skip] already cloned (git): $node_dir"
  elif [[ -f "$node_dir/__init__.py" ]]; then
    # Directory exists with source files but no .git — typically the case for
    # isolated instances, because start_multi_stack.sh's sync_tree() rsyncs the
    # template's custom_nodes/ with `--exclude .git`. The files are functionally
    # complete; we just proceed to install deps and link models.
    log "[skip] already present (non-git, rsync'd from template): $node_dir"
  elif [[ -d "$node_dir" ]]; then
    # Directory exists but looks incomplete (no .git and no __init__.py).
    # Remove and re-clone to guarantee a usable install.
    log "[reinstall] incomplete directory, removing and re-cloning: $node_dir"
    rm -rf "$node_dir"
    git clone --depth 1 "$COMFY_NODE_REPO" "$node_dir"
  else
    log "[clone] $COMFY_NODE_REPO → $node_dir"
    git clone --depth 1 "$COMFY_NODE_REPO" "$node_dir"
  fi
done

# --------------------------------------------------------------------
# 3. Install python deps for comfyui_controlnet_aux (shared venv)
#    Pick the FIRST target's requirements.txt to install once.
# --------------------------------------------------------------------
first_node="${NODE_TARGETS[0]}/$COMFY_NODE_NAME"
if [[ -f "$first_node/requirements.txt" ]]; then
  log "[pip] installing deps from $first_node/requirements.txt into $PIP_BIN"
  "$PIP_BIN" install --no-input -r "$first_node/requirements.txt"
else
  log "[warn] $first_node/requirements.txt not found, skipping pip install"
fi

# --------------------------------------------------------------------
# 4. Download DWPose ONNX models to central location
# --------------------------------------------------------------------
mkdir -p "$DWPOSE_DIR"

download_if_missing() {
  local url="$1"
  local dst="$2"
  if [[ -s "$dst" ]]; then
    log "[skip] $(basename "$dst") already exists ($(du -h "$dst" | cut -f1))"
    return 0
  fi
  log "[download] $url → $dst"
  local auth_header=""
  if [[ -n "${HF_TOKEN:-}" ]]; then
    auth_header="Authorization: Bearer $HF_TOKEN"
  fi
  if [[ -n "$auth_header" ]]; then
    curl -L -C - -H "$auth_header" -o "$dst" "$url"
  else
    curl -L -C - -o "$dst" "$url"
  fi
  [[ -s "$dst" ]] || die "download failed: $dst"
  log "[done] $(basename "$dst") ($(du -h "$dst" | cut -f1))"
}

download_if_missing "$YOLOX_URL" "$DWPOSE_DIR/yolox_l.onnx"
download_if_missing "$DWLL_URL"  "$DWPOSE_DIR/dw-ll_ucoco_384.onnx"

# --------------------------------------------------------------------
# 5. Symlink DWPose ONNX into each node's ckpts/ directory
#    (comfyui_controlnet_aux looks up model files under its ckpts/ subdir)
# --------------------------------------------------------------------
for target in "${NODE_TARGETS[@]}"; do
  ckpts_dir="$target/$COMFY_NODE_NAME/ckpts"
  mkdir -p "$ckpts_dir"
  for onnx in yolox_l.onnx dw-ll_ucoco_384.onnx; do
    link="$ckpts_dir/$onnx"
    src="$DWPOSE_DIR/$onnx"
    if [[ -L "$link" && "$(readlink -f "$link")" == "$src" ]]; then
      log "[skip] symlink exists: $link"
    else
      rm -f "$link"
      ln -s "$src" "$link"
      log "[link] $link → $src"
    fi
  done
done

# --------------------------------------------------------------------
# 6. Download FLUX ControlNet Union to central models/controlnet/
# --------------------------------------------------------------------
mkdir -p "$CONTROLNET_DIR"
download_if_missing "$FLUX_CN_URL" "$CONTROLNET_DIR/$FLUX_CN_FILE"

# --------------------------------------------------------------------
# 7. Summary
# --------------------------------------------------------------------
log ""
log "=== installation summary ==="
log "custom node installed into ${#NODE_TARGETS[@]} location(s)"
log "DWPose models:"
log "  - $DWPOSE_DIR/yolox_l.onnx"
log "  - $DWPOSE_DIR/dw-ll_ucoco_384.onnx"
log "FLUX ControlNet:"
log "  - $CONTROLNET_DIR/$FLUX_CN_FILE"
log ""
log "next steps:"
log "  bash scripts/start_multi_stack.sh   # restart all ComfyUI instances"
log "  bash scripts/verify_controlnet.sh   # validate install and compatibility"
