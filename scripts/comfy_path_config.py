#!/usr/bin/env python3
from __future__ import annotations

import re
from pathlib import Path


def _yaml_single_quoted(value: str) -> str:
    return "'" + value.replace("'", "''") + "'"


def build_managed_block(config_name: str, models_root: Path) -> str:
    models_root = models_root.expanduser().resolve()
    lines = [
        f"{config_name}:",
        f"    base_path: {_yaml_single_quoted(str(models_root))}",
        "    is_default: true",
        "    diffusion_models: |",
        "        diffusion_models",
        "        unet",
        "    loras: loras",
        "    vae: vae",
        "    text_encoders: text_encoders",
        "    checkpoints: checkpoints",
        "    clip: clip",
        "    clip_vision: clip_vision",
        "    controlnet: controlnet",
        "    pulid: pulid",
        "    embeddings: embeddings",
        "    upscale_models: upscale_models",
        "    latent_upscale_models: latent_upscale_models",
        "    model_patches: model_patches",
    ]
    return "\n".join(lines)


def upsert_extra_model_paths(comfy_root: Path, config_name: str, models_root: Path) -> Path:
    comfy_root = comfy_root.expanduser().resolve()
    target_file = comfy_root / "extra_model_paths.yaml"
    target_file.parent.mkdir(parents=True, exist_ok=True)

    start = f"# >>> {config_name} (managed by chat_image) >>>"
    end = f"# <<< {config_name} (managed by chat_image) <<<"
    block = "\n".join([start, build_managed_block(config_name, models_root), end]) + "\n"

    if target_file.exists():
        current = target_file.read_text(encoding="utf-8")
    else:
        current = "# Auto-generated by chat_image scripts\n"

    pattern = re.compile(re.escape(start) + r".*?" + re.escape(end) + r"\n?", re.DOTALL)
    cleaned = re.sub(pattern, "", current).rstrip()
    if cleaned:
        next_content = cleaned + "\n\n" + block
    else:
        next_content = block
    target_file.write_text(next_content, encoding="utf-8")
    return target_file
