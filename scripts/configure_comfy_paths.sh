#!/usr/bin/env bash
# Write/update ComfyUI extra_model_paths.yaml so it points at this project's
# ./models directory. Idempotent: replaces the block delimited by our managed
# markers, leaving the rest of the file untouched.
#
# Usage: configure_comfy_paths.sh --models-root <dir> --comfy-root <dir> [--config-name <key>]
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
PROJECT_ROOT="$(cd "$SCRIPT_DIR/.." && pwd)"

MODELS_ROOT="${MODELS_ROOT:-$PROJECT_ROOT/models}"
COMFY_ROOT="${COMFYUI_ROOT:-$HOME/ComfyUI}"
CONFIG_NAME="${COMFY_EXTRA_CONFIG_NAME:-chat_image_models}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --models-root) MODELS_ROOT="$2"; shift 2 ;;
    --comfy-root)  COMFY_ROOT="$2";  shift 2 ;;
    --config-name) CONFIG_NAME="$2"; shift 2 ;;
    *) echo "[configure_comfy_paths] ignoring unknown arg: $1" >&2; shift ;;
  esac
done

mkdir -p "$MODELS_ROOT"
MODELS_ROOT="$(cd "$MODELS_ROOT" && pwd)"
mkdir -p "$COMFY_ROOT"
COMFY_ROOT="$(cd "$COMFY_ROOT" && pwd)"

target="$COMFY_ROOT/extra_model_paths.yaml"
start="# >>> ${CONFIG_NAME} (managed by chat_image) >>>"
end="# <<< ${CONFIG_NAME} (managed by chat_image) <<<"

# YAML single-quote escaping: ' -> ''
q="${MODELS_ROOT//\'/\'\'}"

block="$(cat <<EOF
${start}
${CONFIG_NAME}:
    base_path: '${q}'
    is_default: true
    diffusion_models: |
        diffusion_models
        unet
    loras: loras
    vae: vae
    text_encoders: text_encoders
    checkpoints: checkpoints
    clip: clip
    clip_vision: clip_vision
    controlnet: controlnet
    pulid: pulid
    embeddings: embeddings
    upscale_models: upscale_models
    latent_upscale_models: latent_upscale_models
    model_patches: model_patches
${end}
EOF
)"

if [[ -f "$target" ]]; then
  current="$(cat "$target")"
else
  current="# Auto-generated by chat_image scripts"
fi

# Drop any existing managed block (markers inclusive), then trailing blank lines.
cleaned="$(printf '%s\n' "$current" \
  | awk -v s="$start" -v e="$end" '$0==s{skip=1} skip==0{print} $0==e{skip=0}' \
  | awk 'NF{nb=NR} {a[NR]=$0} END{for(i=1;i<=nb;i++)print a[i]}')"

{
  if [[ -n "$cleaned" ]]; then
    printf '%s\n\n' "$cleaned"
  fi
  printf '%s\n' "$block"
} > "$target"

echo "Updated: $target"
echo "Models root: $MODELS_ROOT"
echo "Config key : $CONFIG_NAME"
